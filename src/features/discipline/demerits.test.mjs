// --- waiveDemeritSchema ------------------------------------------------

test("waiveDemeritSchema trims reason and enforces 3 to 500 characters", () => {
  const minOk = waiveDemeritSchema.safeParse({
    requestKey: KEY_1,
    demeritId: KEY_2,
    reason: "  abc  ",
  });
  assert.equal(minOk.success, true);
  if (minOk.success) assert.equal(minOk.data.reason, "abc");

  const maxOk = waiveDemeritSchema.safeParse({
    requestKey: KEY_1,
    demeritId: KEY_2,
    reason: ` ${"x".repeat(500)} `,
  });
  assert.equal(maxOk.success, true);

  for (const badReason of ["", "   ", "ab", "  ab  ", "x".repeat(501)]) {
    assert.equal(
      waiveDemeritSchema.safeParse({ requestKey: KEY_1, demeritId: KEY_2, reason: badReason }).success,
      false,
      `reason=${badReason.slice(0, 12)}`
    );
  }
});

test("waiveDemeritSchema rejects invalid requestKey or demeritId UUIDs", () => {
  assert.equal(
    waiveDemeritSchema.safeParse({ requestKey: "not-a-uuid", demeritId: KEY_2, reason: "Entered in error" }).success,
    false
  );
  assert.equal(
    waiveDemeritSchema.safeParse({ requestKey: KEY_1, demeritId: "not-a-uuid", reason: "Entered in error" }).success,
    false
  );
});
